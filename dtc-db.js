function dtcFamily(code) {
  const sys = { P: 'Powertrain', C: 'Chassis', B: 'Body', U: 'Network' }[code[0]] || '?';
  if (code[1] === '1' || code[1] === '3')
    return sys + ' — manufacturer-specific (Hyundai/Kia); look it up in a Kia-specific reference';
  const p3 = {
    '0': 'fuel & air metering, auxiliary emission controls',
    '1': 'fuel & air metering',
    '2': 'fuel & air metering (injector circuit)',
    '3': 'ignition system or misfire',
    '4': 'auxiliary emission controls (EGR, EVAP, catalyst)',
    '5': 'vehicle speed & idle control',
    '6': 'computer output circuits',
    '7': 'transmission', '8': 'transmission', '9': 'transmission',
    'A': 'hybrid propulsion', 'B': 'hybrid propulsion', 'C': 'hybrid propulsion',
  };
  const area = code[0] === 'P' ? (p3[code[2]] || 'unknown subsystem') : 'see subsystem chart';
  return sys + ' — generic, subsystem: ' + area;
}

function describeDtc(code) {
  return {
    code,
    desc: DTC_DB[code] || null,
    family: dtcFamily(code),
  };
}
